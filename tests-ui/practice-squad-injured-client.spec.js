import {test,expect} from '@playwright/test';
import {createSession} from '../src/runtime/bootstrap.js';
import {applyInjury} from '../src/engine/injurySystem.js';
import {declareStandardElevation,settleStandardElevationGame,standardElevationGame} from '../src/domain/standardElevations.js';
import {startStaticClientHost,configureClient,createClientLeague,readClient,assertRuntime,saveSlot,waitGameReady} from './helpers/static-client.js';
let host;
test.beforeAll(async()=>{host=await startStaticClientHost();});
test.afterAll(async()=>{await host?.close();});
for(const worker of [true,false])test(`built ${worker?'worker':'in-page'} Practice Squad/Injured command retains salary rights after save and reload`,async({page})=>{
 const session=createSession({seed:117,startYear:2026,controlledTeamId:'BUF'});session.league.teamCapOverride.BUF=1e9;
 const p=session.league.players.find(p=>p.teamId==='BUF'&&p.rosterSlot==='practice'&&p.experience===0&&!p.injury?.weeksRemaining&&!p.suspensionWeeks);
 const game=standardElevationGame({year:2026,week:1,homeTeamId:'BUF',awayTeamId:'MIA'});
 expect(declareStandardElevation({league:session.league,player:p,teamId:'BUF',game,capSpace:1e8}).ok).toBe(true);
 settleStandardElevationGame({league:session.league,result:{...game,winnerId:'BUF'}});
 applyInjury(p,{type:'Out 6W',weeksRemaining:6},{gameId:game.gameId});
 const terms=structuredClone(p.contract),appearance=(session.getPlayerProfile(p.id)).player.appearance;
 await configureClient(page,worker);await createClientLeague(page,host.origin,{seed:117,year:2026,team:'BUF',mode:'play'});await assertRuntime(page,worker);
 const post=async(path,body)=>page.evaluate(async({path,body})=>{const{createApiClient}=await import('./lib/api/createApiClient.js');try{return await createApiClient()(path,{method:'POST',body});}catch(e){return e.payload;}},{path,body});
 expect((await post('/api/snapshot/import',{snapshot:session.toSnapshot()})).ok).toBe(true);
 expect((await post('/api/roster/designation',{teamId:'BUF',playerId:p.id,designation:'ps-injured',active:true})).ok).toBe(true);
 const before=(await readClient(page,'/api/snapshot/export')).snapshot;
 expect(before.league.players.find(q=>q.id===p.id).contract).toEqual(terms);
 expect(before.league.players.find(q=>q.id===p.id).elevationInjuryPay.episodes[0].status).toBe('active');
 await saveSlot(page,'practice-injured');await page.reload();await waitGameReady(page);await assertRuntime(page,worker);
 const restored=(await readClient(page,'/api/snapshot/export')).snapshot;
 const actual=restored.league.players.find(q=>q.id===p.id);expect(actual.rosterSlot).toBe('reserve');expect(actual.reserveStatus.kind).toBe('ps-injured');expect(actual.contract).toEqual(terms);
 expect((await readClient(page,`/api/player?playerId=${p.id}`)).profile.player.appearance).toEqual(appearance);
 const bad=structuredClone(restored);bad.league.players.find(q=>q.id===p.id).reserveStatus.countsAgainstReturnLimit=false;
 expect((await post('/api/snapshot/import',{snapshot:bad})).ok).toBe(false);
 expect((await post('/api/roster/designation',{teamId:'BUF',playerId:p.id,designation:'ps-injured',active:false})).ok).toBe(false);
 const after=(await readClient(page,'/api/snapshot/export')).snapshot;
 delete restored.league.observability;delete after.league.observability;expect(after).toEqual(restored);
});
